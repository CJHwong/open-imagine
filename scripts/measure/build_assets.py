"""Make the references the parity run needs, on the machine that owns the engines.

One picture is generated by the image backend and resized, two speeches are generated by the
voice backend with their scripts written down, and the audio references are slices of one
recording. Every case then cites a file here, so both engines read the same bytes.
"""

import argparse
import base64
import hashlib
import json
import shutil
import time
import urllib.request
import wave
from pathlib import Path

from PIL import Image

# The same sentence parity_matrix.py sends. The references must show what the cases ask for,
# or an edit case cites a picture that does not hold the thing its prompt names.
PICTURE = (
    "A close still life of two red enamel coffee pots on a pale stone windowsill, looking out to "
    "sea. The tall pot stands on the left third, the short one a hand's width to its right, both "
    "dented and lightly dusty, handles turned to the right. Beyond the sill the sea is flat and "
    "deep blue under a pale morning sky, out of focus. Low sun comes from the left, warm on the "
    "enamel and casting long shadows across the stone. Shot at eye level with a 50 mm lens at "
    "f/2, shallow depth of field, the pots sharp against the soft sea behind. Nothing else "
    "shares the sill."
)
SHORT = "The tide is low and the boats are still, and the wall is quiet."
LONG = (
    "Every morning the fisherman walked the same wall. He knew the tide by the sound it made "
    "against the stones, and he knew the weather by the colour of the water beyond it."
)
SIZES = {
    "ref-512.png": (512, 512),
    "ref-1600x900.png": (1600, 900),
    "ref-2048.png": (2048, 2048),
    "ref-4032x3024.png": (4032, 3024),
    "ref-768x512.png": (768, 512),
}
MANIFEST_NAME = "assets.sha256"


def post(base: str, body: dict) -> dict:
    request = urllib.request.Request(
        base + "/api/v1/operations",
        data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=120) as answer:
        return json.loads(answer.read())


def wait(base: str, operation: str, deadline: float) -> dict:
    """Poll until the operation ends. A server that never answers must not stall a
    whole comparison, so the caller sets how long one asset may take."""
    started = time.time()
    while True:
        if time.time() - started > deadline:
            raise SystemExit(f"{operation} did not end within {deadline:g} s")
        with urllib.request.urlopen(f"{base}/api/v1/operations/{operation}", timeout=120) as answer:
            state = json.loads(answer.read())
        if state["status"] in ("succeeded", "failed", "cancelled"):
            return state
        time.sleep(1.0)


def write_manifest(directory: Path, manifest: Path) -> Path:
    """One line per asset, so a machine that did not build them can prove it reads the
    same bytes. This is the file the runner checks before it sends anything."""
    lines = [
        f"{hashlib.sha256(path.read_bytes()).hexdigest()}  {path.name}"
        for path in sorted(directory.iterdir())
        if path.is_file()
    ]
    scratch = manifest.with_suffix(".tmp")
    scratch.write_text("\n".join(lines) + "\n")
    scratch.replace(manifest)
    return manifest


def publish(staging: Path, assets: Path, manifest: Path) -> None:
    """Put the new set in place, and only then the manifest that describes it.

    The set is assembled beside the one in use, so a build that dies costs time and not the
    fixtures. A crash between the two renames leaves no assets folder rather than a mixed
    one, and the runner refuses that loudly.
    """
    previous = assets.with_name(assets.name + ".old")
    shutil.rmtree(previous, ignore_errors=True)
    if assets.exists():
        assets.rename(previous)
    staging.rename(assets)
    (assets / MANIFEST_NAME).replace(manifest)
    shutil.rmtree(previous, ignore_errors=True)


def run(base: str, body: dict, name: str, assets: Path, deadline: float) -> Path:
    started = time.time()
    accepted = post(base, body)
    state = wait(base, accepted["id"], deadline)
    if state["status"] != "succeeded":
        raise SystemExit(f"{name} ended {state['status']}: {state.get('error')}")
    with urllib.request.urlopen(f"{base}/api/v1/operations/{accepted['id']}/result", timeout=600) as answer:
        content = answer.read()
    # An image result crosses as JSON with the picture inside it; audio is the file itself.
    if content[:1] == b"{":
        content = base64.b64decode(json.loads(content)["images"][0]["png_base64"])
    target = assets / name
    target.write_bytes(content)
    print(f"{name}: {round(time.time() - started, 1)} s, {len(content)} bytes", flush=True)
    return target


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", default="http://127.0.0.1:8899")
    parser.add_argument("--work", default="/tmp/parity")
    parser.add_argument("--image-backend", required=True)
    parser.add_argument("--voice-backend", required=True)
    parser.add_argument("--audio-source", default="", help="a recording to slice for transcribe and cover")
    parser.add_argument("--deadline", type=float, default=900.0, help="seconds one asset may take")
    parser.add_argument("--force", action="store_true", help="build again over an asset directory that exists")
    arguments = parser.parse_args()

    assets = Path(arguments.work) / "assets"
    manifest = assets.parent / MANIFEST_NAME
    if manifest.is_file() and not arguments.force:
        raise SystemExit(
            f"{manifest} exists, so these assets already have an owner. Every machine must read "
            "those bytes, so copying the directory beats building it again. Pass --force to rebuild."
        )
    staging = assets.parent / "assets.new"
    shutil.rmtree(staging, ignore_errors=True)
    staging.mkdir(parents=True)
    print("picture", flush=True)
    source = run(
        arguments.base,
        {
            "kind": "image",
            "backend": arguments.image_backend,
            "mode": "generate",
            "prompt": PICTURE,
            "size": "1024x1024",
            "steps": 8,
            "guidance": 1.0,
            "seed": 7,
        },
        "picture-1024.png",
        staging,
        arguments.deadline,
    )
    with Image.open(source) as picture:
        for name, size in SIZES.items():
            picture.convert("RGB").resize(size, Image.Resampling.LANCZOS).save(staging / name)
            print(name, size, flush=True)

    run(
        arguments.base,
        {"kind": "voice", "backend": arguments.voice_backend, "mode": "generate", "text": SHORT, "seed": 7},
        "voice-short.wav",
        staging,
        arguments.deadline,
    )
    run(
        arguments.base,
        {"kind": "voice", "backend": arguments.voice_backend, "mode": "generate", "text": LONG, "seed": 7},
        "voice-long.wav",
        staging,
        arguments.deadline,
    )

    if arguments.audio_source:
        with wave.open(arguments.audio_source) as handle:
            rate, channels, width = handle.getframerate(), handle.getnchannels(), handle.getsampwidth()
            for name, length in (("music-10s.wav", 10.0), ("music-15s.wav", 15.0)):
                handle.setpos(0)
                frames = handle.readframes(int(length * rate))
                with wave.open(str(staging / name), "wb") as target:
                    target.setframerate(rate)
                    target.setnchannels(channels)
                    target.setsampwidth(width)
                    target.writeframes(frames)
                print(name, length, flush=True)

    (staging / "scripts.json").write_text(
        json.dumps({"short": SHORT, "long": LONG, "picture": PICTURE}, indent=1) + "\n"
    )
    write_manifest(staging, staging / MANIFEST_NAME)
    publish(staging, assets, manifest)
    print("assets ready in", assets, "listed in", manifest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
