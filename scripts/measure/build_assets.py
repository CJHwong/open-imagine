"""Make the references the parity run needs, on the machine that owns the engines.

One picture is generated by the image backend and resized, two speeches are generated by the
voice backend with their scripts written down, and the audio references are slices of one
recording. Every case then cites a file here, so both engines read the same bytes.
"""

import argparse
import base64
import json
import time
import urllib.request
import wave
from pathlib import Path

from PIL import Image

PICTURE = (
    "A weathered fisherman mends a net on a harbour wall at dawn, warm low light, calm water "
    "and open sky behind him, fine rope detail, a painted sign reading HARBOUR"
)
SHORT = "The tide is low and the boats are still, and the wall is quiet."
LONG = (
    "Every morning the fisherman walked the same wall. He knew the tide by the sound it made "
    "against the stones, and he knew the weather by the colour of the water beyond it."
)
SIZES = {
    "ref-512.png": (512, 512),
    "ref-1600x900.png": (1600, 900),
    "ref-2048.png": (2048, 2048),
    "ref-4032x3024.png": (4032, 3024),
    "ref-768x512.png": (768, 512),
}


def post(base: str, body: dict) -> dict:
    request = urllib.request.Request(
        base + "/api/v1/operations",
        data=json.dumps(body).encode(),
        headers={"Content-Type": "application/json"},
        method="POST",
    )
    with urllib.request.urlopen(request, timeout=120) as answer:
        return json.loads(answer.read())


def wait(base: str, operation: str) -> dict:
    while True:
        with urllib.request.urlopen(f"{base}/api/v1/operations/{operation}", timeout=120) as answer:
            state = json.loads(answer.read())
        if state["status"] in ("succeeded", "failed", "cancelled"):
            return state
        time.sleep(1.0)


def run(base: str, body: dict, name: str, assets: Path) -> Path:
    started = time.time()
    accepted = post(base, body)
    state = wait(base, accepted["id"])
    if state["status"] != "succeeded":
        raise SystemExit(f"{name} ended {state['status']}: {state.get('error')}")
    with urllib.request.urlopen(f"{base}/api/v1/operations/{accepted['id']}/result", timeout=600) as answer:
        content = answer.read()
    # An image result crosses as JSON with the picture inside it; audio is the file itself.
    if content[:1] == b"{":
        content = base64.b64decode(json.loads(content)["images"][0]["png_base64"])
    target = assets / name
    target.write_bytes(content)
    print(f"{name}: {round(time.time() - started, 1)} s, {len(content)} bytes", flush=True)
    return target


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base", default="http://127.0.0.1:8899")
    parser.add_argument("--work", default="/tmp/parity")
    parser.add_argument("--image-backend", required=True)
    parser.add_argument("--voice-backend", required=True)
    parser.add_argument("--audio-source", default="", help="a recording to slice for transcribe and cover")
    arguments = parser.parse_args()

    assets = Path(arguments.work) / "assets"
    assets.mkdir(parents=True, exist_ok=True)
    print("picture", flush=True)
    source = run(
        arguments.base,
        {
            "kind": "image",
            "backend": arguments.image_backend,
            "mode": "generate",
            "prompt": PICTURE,
            "size": "1024x1024",
            "steps": 8,
            "guidance": 1.0,
            "seed": 7,
        },
        "picture-1024.png",
        assets,
    )
    with Image.open(source) as picture:
        for name, size in SIZES.items():
            picture.convert("RGB").resize(size, Image.Resampling.LANCZOS).save(assets / name)
            print(name, size, flush=True)

    run(
        arguments.base,
        {"kind": "voice", "backend": arguments.voice_backend, "mode": "generate", "text": SHORT, "seed": 7},
        "voice-short.wav",
        assets,
    )
    run(
        arguments.base,
        {"kind": "voice", "backend": arguments.voice_backend, "mode": "generate", "text": LONG, "seed": 7},
        "voice-long.wav",
        assets,
    )

    if arguments.audio_source:
        with wave.open(arguments.audio_source) as handle:
            rate, channels, width = handle.getframerate(), handle.getnchannels(), handle.getsampwidth()
            for name, length in (("music-10s.wav", 10.0), ("music-15s.wav", 15.0)):
                handle.setpos(0)
                frames = handle.readframes(int(length * rate))
                with wave.open(str(assets / name), "wb") as target:
                    target.setframerate(rate)
                    target.setnchannels(channels)
                    target.setsampwidth(width)
                    target.writeframes(frames)
                print(name, length, flush=True)

    (assets / "scripts.json").write_text(
        json.dumps({"short": SHORT, "long": LONG, "picture": PICTURE}, indent=1) + "\n"
    )
    print("assets ready in", assets)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
